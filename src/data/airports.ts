export function findAirport(code: string): Airport | undefined {
  return US_AIRPORTS.find((a) => a.code === code.toUpperCase());
}

export function searchAirports(query: string, limit = 8): Airport[] {
  const q = query.trim().toLowerCase();
  if (!q) return US_AIRPORTS.slice(0, limit);

  const starts: Airport[] = [];
  const contains: Airport[] = [];

  for (const airport of US_AIRPORTS) {
    const code = airport.code.toLowerCase();
    const city = airport.city.toLowerCase();
    const name = airport.name.toLowerCase();

    if (code.startsWith(q) || city.startsWith(q)) {
      starts.push(airport);
    } else if (code.includes(q) || city.includes(q) || name.includes(q)) {
      contains.push(airport);
    }
  }

  return [...starts, ...contains].slice(0, limit);
}
